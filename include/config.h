// ===== ДЛИНА ПУТИ В КАДРЕ =====
// Старшие два бита байта path_len задают размер хэша одного ретранслятора, младшие шесть —
// число хопов. Вся сеть обязана считать одинаково, поэтому значение одно на все платы:

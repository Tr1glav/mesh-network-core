#define OTA_ACKSTART_GAP_MS 150
// Сколько бот ждёт после ackstart, прежде чем слать первую пачку. Это НЕ «сколько-нибудь»:
// столько же занимает отправка ackstart у сенсора (2 кадра в эфире + пауза), и ждать
// меньше — значит уйти на быстрый канал раньше сенсора и потерять первую пачку.
#define OTA_FAST_SETTLE_MS  1200
// Быстрый канал — GFSK. Параметры связаны между собой: полоса приёмника должна
// покрывать 2*(девиация + скорость/2) — правило Карсона, — а девиация задаёт индекс
// модуляции 2*dev/br, который для надёжного приёма держат около единицы.
// Прошлая попытка поднять скорость до 250 кбит/с оставила девиацию 50 кГц и полосу
// 234 кГц: индекс падал до 0.4, а полоса была вдвое уже нужной — связь и разваливалась.
#define OTA_FSK_BR          250.0   // кбит/с
#define OTA_FSK_DEV         125.0   // кГц: индекс модуляции 1.0
#define OTA_FSK_RXBW        467.0   // кГц: ближайшее к 2*(125+125)=500, что умеет SX1262
#define OTA_FSK_PREAMBLE    32      // бит
// Чанков в пачке до подтверждения. Предел — 16: маска подтверждений uint16.
// При 8 на каждые 8 кадров приходился обмен квитанцией, и в замере выходило 3.8 КБ/с
// при теоретических 12.5 КБ/с для GFSK 100 кбит/с — ждём ответ вдвое реже.
#define OTA_WINDOW          16
// пауза между кадрами пачки: сенсор должен вычитать кадр и вернуться в RX до следующего
// Измерено на стенде: при 8 мс сессия занимает 56.7 с, при 4 мс — 61.6 с. Меньшая пауза
// экономит 4.4 с ожидания, но сенсор перестаёт успевать: кадров уходит 1259 вместо 1177,
// опросов 10 вместо 4, а каждый опрос стоит 400 мс. Это граница возможностей приёмника.
#define OTA_BURST_GAP_MS    8

// Сенсорная сторона OTA
#define OTA_SENSOR_STALL_MS 60000
// без первого чанка сенсор возвращается на штатный канал; бот выжидает это время перед повтором
#define OTA_SENSOR_FIRST_CHUNK_MS 5000
// Весь образ принят, остался фрейм DONE. Бот повторяет его каждые OTA_END_TIMEOUT_MS и
// сдаётся после OTA_END_TIMEOUT_MS*(OTA_MAX_RETRIES+2) ≈ 18 с. Этот сторож кроет то же
// окно с запасом: потерялся DONE — сенсор сам возвращается на штатный канал, а не сидит
// весь OTA_SENSOR_STALL_MS (60 с) в быстром, глухой к сети.
#define OTA_SENSOR_END_MS   20000

// ===== МЕДЛЕННЫЙ РЕЖИМ: ПРОШИВКА ПО САМОМУ MESHCORE =====
// Быстрый режим идёт сырыми FSK-кадрами, и ретрансляторы их не переносят: дальше
// OTA_RADIO_MAX_HOPS он бесполезен. Медленный режим — противоположный размен: образ едет
// обычными групповыми сообщениями сенсорного канала, то есть шифруется, ретранслируется и
// доходит туда же, куда доходит любое сообщение сети. Платой за это становится скорость.
//
// Чанк: в открытый текст группового сообщения влезает GROUP_TEXT_MAX_PLAIN минус метка
// времени, тип и префикс «Имя: ». 128 байт данных дают 172 символа base64 плюс короткий
// заголовок — помещается с запасом даже при длинном имени узла.
//
// base64, а не hex: hex удваивает объём, а образ и без того едет часами.
#ifndef OTA_SLOW_CHUNK_BYTES
#define OTA_SLOW_CHUNK_BYTES 128
#endif
// Чанков между подтверждениями. Подтверждение кумулятивное («жду такой-то»), как в TCP:
// отправителю не нужна маска, а узлу — помнить дыры. Окно маленькое, потому что каждое
// сообщение занимает эфир на полсекунды и повторяется флудом.
#define OTA_SLOW_WINDOW 8
// Пауза между чанками окна — БОЛЬШЕ, чем время ретрансляции. Это не запас «на всякий
// случай»: ретрансляторы переносят наш чанк с задержкой до RELAY_DELAY_MAX_MS, и при паузе
// в полторы секунды следующий чанк уходил в эфир поверх ретрансляции предыдущего. Мы сами
// себе создавали коллизии — и одновременно глушили всё, что в это время говорят другие: на
// проверке связи это было видно как потерянные пинги.
//
// Цена — время: сессия растягивается примерно вдвое. Медленный режим и задуман как размен
// скорости на дальность, и правильнее отдать эфир, чем спорить за него с собственными
// ретрансляциями.
#define OTA_SLOW_GAP_MS (RELAY_DELAY_MAX_MS + 500)
// ===== МАЯТНИК: В КАНАЛЕ ГОВОРИТ ТОЛЬКО ОДИН =====
// Радио полудуплексное, и эфир здесь общий: пока ведущий шлёт окно, узел отвечать не должен —
// его подтверждение придёт в занятый эфир, и ведущий его не услышит. Поэтому время поделено
// на две фазы, и каждая сторона знает, когда её очередь.
//
// Фаза данных: ведущий шлёт окно чанков и замолкает.
// Фаза ответа: ведущий МОЛЧИТ OTA_SLOW_RESP_MS, узел отвечает внутри этого окна.
//
// Длина окна ответа выведена из того, что реально происходит в эфире, а не подобрана на глаз:
//   RELAY_DELAY_MAX_MS  ретрансляторы переносят наш последний чанк до 2.5 с после нас;
//   + передача ack      само подтверждение ~0.5 с на SF8;
//   + ретрансляции ack  его тоже разносят до 2.5 с;
//   + запас.
// Отвечать раньше, чем утихнет волна ретрансляций нашего же чанка, бессмысленно — поэтому
// узел выжидает OTA_SLOW_ACK_DELAY_MS от последнего принятого чанка и только потом говорит.
// Сама пауза 1200 мс покрывает и хвост переизданий чанка, и время в эфире у подтверждения.
#define OTA_SLOW_ACK_DELAY_MS 1200
// Разброс: узлов в канале может быть несколько, и отвечать одновременно им незачем.
#define OTA_SLOW_ACK_JITTER_MS 600
// Столько ждёт ведущий, пока узел отвечает: пауза узла, её разброс, переиздание
// подтверждения ретрансляторами и время в эфире.
#define OTA_SLOW_RESP_MS (OTA_SLOW_ACK_DELAY_MS + OTA_SLOW_ACK_JITTER_MS + \
                          RELAY_DELAY_MAX_MS + FRAME_AIRTIME_MS)
// Сколько ведущий ждёт подтверждения: ровно окно ответа. Дольше ждать нечего — узел либо
// ответил в свою фазу, либо не ответил вовсе.
#define OTA_SLOW_ACK_TIMEOUT_MS OTA_SLOW_RESP_MS
// Столько повторов окна подряд без единого подтверждения — и сессия признаётся мёртвой.
// Число большое намеренно: медленный режим — последнее средство, им шьют узел, до которого
// иначе не дотянуться вовсе. Сдаться на пятой попытке значит оставить его непрошитым, хотя
// связь всего лишь «плохая», а не «отсутствует»: пропущенное окно повторяется, и шанс есть у
// каждого повтора. Час ожидания дешевле поездки к узлу.
#define OTA_SLOW_MAX_RETRIES 20
// Пауза между повторами окна растёт: сеть могла замолчать не на секунду, а надолго — сосед
// занял канал, узел перезагружается, прошла гроза. Продолжать долбить с прежним темпом
// значит мешать и себе, и всем.
#define OTA_SLOW_RETRY_STEP_MS 5000
#define OTA_SLOW_RETRY_MAX_MS 60000
// Узел, не получивший ни одного чанка за это время, выходит из приёма: отправитель мог
// перезагрузиться, и ждать его вечно, держа флеш открытым, незачем. Полчаса — с запасом на
// все повторы ведущего: выйти раньше него значит потерять уже принятую часть образа.
#define OTA_SLOW_STALL_MS (30UL * 60 * 1000)
// Сколько эфир считается занятым после последнего услышанного чанка. По этому окну узлы,
// которые к сессии не относятся, придерживают свои ответы: отвечать поверх чанка — значит
// потерять и ответ, и чанк. Считается от ЛЮБОГО услышанного чанка, поэтому правило работает
// у всех, кто в канале, а не только у участников прошивки.
#define OTA_SLOW_AIR_BUSY_MS (RELAY_DELAY_MAX_MS + 700)

// Сообщения медленного режима. Данные — "osd:<seq>:<base64>", остальное управление.
#define OTA_SLOW_MSG_START "ota:slow:"     // <target>:<байт>:<crc32>:<чанков>
#define OTA_SLOW_MSG_DATA  "osd:"          // <seq>:<base64 чанка>
#define OTA_SLOW_MSG_ACK   "ota:sack:"     // <номер следующего ожидаемого чанка>

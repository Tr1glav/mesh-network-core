// ===== ВРЕМЕННЫЕ БЮДЖЕТЫ =====
// Таймауты и паузы в протоколе нельзя задавать по отдельности: каждая передача теперь ждёт
// тишины в канале (CAD) и висит в эфире не меньше FRAME_AIRTIME_MS, а ответ проходит ещё
// и через случайную паузу, и через задержку ретранслятора. Когда их посчитали по одной,
// получилось, что ответ на пинг мог прийти ПОСЛЕ того, как потеря уже засчитана: на
// загруженной сети — то есть ровно там, где теряется и так. Здесь бюджет собирается из
// составляющих, поэтому правка любой из них не рассинхронизирует остальные.

// Сколько времени кадр самого большого размера (GROUP_TEXT_MAX_PLAIN + заголовок, то есть
// самый тяжёлый случай наших сообщений) занимает эфир. Грубая верхняя оценка для
// SF8/BW62.5, её используют расчёты таймаутов: ждать ответа нужно с запасом на время,
// которое кадр просто висит в эфире.
#ifndef FRAME_AIRTIME_MS
#define FRAME_AIRTIME_MS 500
#endif
// Одна передача в худшем случае: дождались тишины в канале (CAD_WAIT_BUDGET_MS) плюс кадр
// в эфире.
#define TX_WORST_MS (CAD_WAIT_BUDGET_MS + FRAME_AIRTIME_MS)
// Переиздание у ретранслятора: пауза перед переизданием, затем своя передача.
#define RELAY_WORST_MS (RELAY_DELAY_MAX_MS + TX_WORST_MS)

// ===== СЛУШАЕМ ЭФИР ПЕРЕД ПЕРЕДАЧЕЙ (CAD) =====
// Радио полудуплексное и канал общий: передача поверх чужой — это два потерянных пакета
// вместо одного доставленного. Оригинальный MeshCore перед каждой отправкой проверяет
// активность в канале и, если занято, откладывает передачу на случайную паузу. У нас этой
// проверки не было — кадр уходил вслепую, и на загруженной сети (а медленная прошивка
// загружает её полностью) сообщения терялись заметно чаще.
//
// Пауза случайная: двум узлам, дождавшимся конца чужой передачи, нельзя стартовать
// одновременно — иначе они столкнутся уже друг с другом.
#ifndef CAD_RETRY_MIN_MS
#define CAD_RETRY_MIN_MS 120
#endif
#ifndef CAD_RETRY_MAX_MS
#define CAD_RETRY_MAX_MS 480
#endif
// Сколько раз ждём освобождения канала, прежде чем передать всё равно. Предел нужен: радио
// может залипнуть в «занято», и молчать вечно хуже, чем рискнуть коллизией.
#ifndef CAD_MAX_TRIES
#define CAD_MAX_TRIES 8
#endif
// Сколько суммарно ждём тишины, прежде чем передать поверх. Предел по попыткам сам по себе
// давал хвост до 8 * 480 = 3.8 с на КАЖДУЮ передачу, а floodSend шлёт копию за копией —
// в худшем случае сообщение уходило в эфир через десяток секунд после нажатия, и ответ на
// него уже не догонял отправителя. Общий предел держит этот хвост в узде.
#ifndef CAD_WAIT_BUDGET_MS
#define CAD_WAIT_BUDGET_MS 1500
#endif

// ===== ПАУЗА ПЕРЕД ПЕРЕИЗДАНИЕМ У РЕТРАНСЛЯТОРА =====
// Случайная пауза разводит по времени ретрансляторов, услышавших один и тот же кадр, — при
// одинаковой паузе они глушили бы друг друга. Заодно отводит переиздание от хвоста
// повторов отправителя: копии теперь разнесены на секунды, и ретранслятор со своей паузой
// в это окно попадает.
//
// Эти два числа остаются в силе и в сборке БЕЗ ретрансляции, потому что через RELAY_WORST_MS
// они входят в бюджеты ожидания (PING_TIMEOUT_MS, PING_MODE_CYCLE_MS, OTA_SLOW_RESP_MS,
// OTA_SLOW_AIR_BUSY_MS). Убирать их оттуда вместе с признаком нельзя: во-первых, признак
// можно включить на отдельном узле, и тогда ждать придётся именно столько; во-вторых, в том
// же канале могут стоять чужие узлы (оригинальный MeshCore), которые ретранслируют независимо
// от наших признаков сборки. Бюджет считается по худшему случаю в ЭФИРЕ, а не по тому, что
// собрано у нас, — иначе ответ, пришедший через чужой ретранслятор, засчитывался бы потерей.
#ifndef RELAY_DELAY_MIN_MS
#define RELAY_DELAY_MIN_MS 1400
#endif
#ifndef RELAY_DELAY_MAX_MS
#define RELAY_DELAY_MAX_MS 2500
#endif

// Пауза перед ответом на /ping и на личное сообщение. Отправитель шлёт своё сообщение
// не один раз, а повторами, и пока он передаёт — радио полудуплексное — он ничего не
// слышит. Ответ, посланный раньше, приходится ровно на эти повторы и пропадает.
// Значение покрывает повторы отправителя с запасом.
// Пауза перед ответом на пинг и личные сообщения. Случайная и с запасом: пока отправитель
// доканчивает свои повторы, он нас не слышит, а при одинаковой паузе несколько узлов
// отвечают одновременно и глушат друг друга.
#define PING_REPLY_DELAY_MIN_MS 1500
#define PING_REPLY_DELAY_MAX_MS 3500
// Ответ на пинг в худшем случае: отложили на паузу, сами ждали тишины в канале, отправили,
// приём отложил ещё на RELAY_DELAY и тоже ждал тишины. Отсюда и таймаут ожидания ниже.
#define PING_RESPONSE_WORST_MS (PING_REPLY_DELAY_MAX_MS + TX_WORST_MS + RELAY_WORST_MS)
// Запас сверх расчётного худшего случая — на считывание флагов радио и на то, что миллис
// в разных местах слегка расходится. Тонкий, но нужен: без него ответ, пришедший ровно в
// граничный момент, засчитывался бы как потеря.
#define PING_TIMEOUT_MARGIN_MS 1500
// Пауза перед ответом на опрос "hello?" со страницы: разводит ответы узлов по времени.
#define HELLO_REPLY_DELAY_MIN_MS 1500
#define HELLO_REPLY_DELAY_MAX_MS 9000
// Не дождались ответа за весь расчётный бюджет — считаем потерей.
#define PING_TIMEOUT_MS     ((unsigned long)(PING_RESPONSE_WORST_MS + PING_TIMEOUT_MARGIN_MS))
#define PING_SHOW_MS        15000UL      // сколько держать результат на экране после режима

// ===== РЕЖИМ ПРОВЕРКИ ДОСТУПНОСТИ =====
// Одиночный запрос отвечает только на «есть ли связь сию секунду», а на границе слышимости
// она то есть, то нет: один потерянный ответ ничего не доказывает, как и один удачный.
// Поэтому проверка — это режим: узел шлёт запросы подряд и показывает на экране выборку —
// сколько ушло, сколько потеряно, разброс времени ответа.
//
// Период: ответ приходит со случайной паузой до PING_REPLY_DELAY_MAX_MS, отвечают оба —
// координатор и прошивальщик, — и каждый ответ уходит флудом. Интервал задан не «десять
// секунд», а считается: закончить передачу запроса, потом весь бюджет ожидания ответа, плюс
// запас. Пока это было круглое число, запрос следующего обмена ложился на хвост
// предыдущего, и терялся уже он — вместе с ответом на него.
#define PING_MODE_CYCLE_MS (TX_WORST_MS + PING_TIMEOUT_MS + 500UL)
#ifndef PING_MODE_INTERVAL_MS
#define PING_MODE_INTERVAL_MS PING_MODE_CYCLE_MS
#endif
// Предел на случай «включили и ушли»: узел работает от аккумулятора, а режим — это передача
// каждые десять секунд и незасыпающий экран. Полчаса выборки хватает на любой вывод.

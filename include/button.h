// ===== Кнопка узла: что значит нажатие =====
// Здесь только смысл нажатия, и к плате он отношения не имеет: окно дребезга, счёт серии
// коротких нажатий, порог долгого удержания, намеренно пустой промежуток между ними и
// правило «пока идёт проверка доступности, её гасит любое короткое нажатие».
//
// От платы нужно ровно три вещи, и все три приходят через хуки mc_platform.h: настроить пин
// и повесить прерывание (mcButtonAttach), прочитать текущий уровень (mcButtonDown) и
// переключить экран (mcScreenToggle). Пин, его подтяжка и номер прерывания в ядро не едут:
// у плат они разные, а у части плат кнопки нет вовсе.
#if FEATURE_BUTTON

// Один раз при старте. Если плата отвечает «кнопки нет», buttonTick() дальше не делает
// ничего: это защита от исторической ошибки, когда FEATURE_BUTTON включали на плате без
// кнопки и digitalRead на пине −1 отдавал LOW, то есть «кнопка нажата навсегда».
void buttonBegin();

// Из расписания задач узла (sensorTasksTick в ядре, под признаком FEATURE_BUTTON):
// разбирает фронты, защёлкнутые прерыванием. Ничего не блокирует.
void buttonTick();

// Зовётся ИЗ ОБРАБОТЧИКА ПРЕРЫВАНИЯ прошивки и больше ниоткуда. Прошивка читает время и
// уровень (это её пин) и отдаёт их сюда; дальше кольцо и разбор — дело ядра. Определение
// помечено IRAM_ATTR: обработчик может сработать во время операции с флешем, и код должен
// лежать в IRAM.
void buttonEdgeCaptured(uint32_t ms, bool down);

#endif // FEATURE_BUTTON

// Применить яркость экрана сразу (команда "bri" из настройки по радио).
void mcUiSetBrightness(uint8_t bri);

// Авто-яркость экрана по времени суток. Расписание и панель — дело прошивки платы:
// ядро только хранит признак в настройке auto_bri и даёт переключить его командой
// "autobri". Где панели нет, работают заглушки: признак всегда выключен.
bool mcUiAutoBrightnessEnabled();
void mcUiAutoBrightnessSetEnabled(bool on);

// Mesh OTA, раздающая сторона (координатор/прошивальщик).
void mcUiOtaAbort(const char *why);
void mcUiOtaProgress(const String &target, uint32_t pct, uint32_t pkts, float rssi, float snr);
void mcUiOtaDone(const String &target);

// ===== ПРИЁМ ДАННЫХ ПО ЭФИРУ (не прошивки) =====
// Mesh OTA везёт N байт с CRC; прошивку ядро кладёт в раздел само, а всё прочее отдаёт
// сюда — куда именно, знает только прошивка платы (карта памяти, разделы, установка
// приложения). Ядро про файловые системы не знает и знать не должно.
//
// Имени груза здесь нет намеренно: по эфиру приходит только «это пакет», а имя лежит
// внутри самого пакета. Значит место назначения выбирает приёмник, и отправитель не может
// записать файл куда ему вздумается.
//
// Заглушки отвечают false, то есть «мне это некуда положить»: сессия честно отказывается
// вместо того, чтобы принять десятки килобайт и выбросить. Плата без карты так и должна
// себя вести.
bool mcOtaDataBegin(uint32_t total);
bool mcOtaDataWrite(const uint8_t *data, size_t n);
bool mcOtaDataApply(); // поток принят целиком и сверен по CRC: применить (установить)
void mcOtaDataAbort();

// Mesh OTA, принимающая сторона (узел).
void mcUiOtaSensorProgress(uint32_t got, uint32_t total, uint32_t pkts, float rssi, float snr);
void mcUiOtaSensorAbort(const char *why, uint32_t rxFrames, uint32_t rxErr);

// Зажечь экран: используется, когда пришла прошивка и нужно показать её ход.
// Имя без приставки mc — историческое: хук появился раньше остальных, и переименование
// задело бы обе прошивки. Новые хуки экрана называются mc*, как ниже.
void screenWake();

// Переключить экран (включить погасший, погасить горящий). Зовёт логика кнопки из ядра на
// долгом удержании; как именно гасится панель — дело прошивки, у плат разные драйверы.
void mcScreenToggle();

// ===== БАТАРЕЯ (узел) =====
bool mcBatteryPresent();
int mcBatteryPercent();   // 0..100; -1 — измерения нет или аккумулятор не подключён
float mcBatteryVoltage(); // вольты; 0 — платы без измерения батареи

// ===== ПОЗИЦИЯ (GPS) =====
// Координаты узла в микроградусах для hello: плата с приёмником отвечает true и пишет
// широту/долготу; без приёмника те поля в heartbeat не дописываются вовсе.
bool mcBoardPosition(int32_t *latUdeg, int32_t *lonUdeg);

// ===== СЕТЬ (узел-прошивальщик) =====
// Объявление "support:<адрес>" полезно только когда WiFi поднялся.
bool mcWifiConnected();
// mcLocalIp() здесь был и удалён: его не звал никто — ни ядро, ни обе прошивки, — а слабая
// заглушка отдавала "0.0.0.0". Контракт платформы описывает то, что действительно нужно; хук
// «на случай, если понадобится» стоит ровно столько же обязательств, сколько настоящий.

// ===== ПЕРИОДИЧЕСКОЕ В ЦИКЛЕ УЗЛА =====
// sensorTasksTick() в ядре держит расписание узла — heartbeat, сторожа сессий, частоту
// процессора, откат несохранённых настроек. Три вещи из этого расписания живут в прошивке,
// потому что зависят от платы, и ядро зовёт их через эти хуки.
//
// Обойтись без хуков нельзя: раньше весь файл лежал двумя копиями в прошивках именно из-за
// этих трёх вызовов, и копии разошлись. Теперь расходиться нечему.
//
// mcUiTick обязаны закрыть ОБЕ прошивки: это гашение экрана в простое и его пробуждение.
// Заглушка здесь означает экран, который никогда не гаснет, а не выключенную функцию.
void mcUiTick();

// ===== РАДИО ЗАНЯЛО ЭФИР =====
// Передача блокирующая: кадр на медленной скорости держит эфир до двух секунд, и всё это
// время главный цикл прошивки стоял — на плате с экраном это замерший интерфейс, и
// профиль ловил такие проходы по 2141 мс. Ядро зовёт этот хук, пока ждёт радио (пауза
// перед передачей и само время эфира), а прошивка решает, чем занять это время.
// Заглушка — delay(1), то есть прежнее поведение: у прошивки без экрана занимать его
// нечем.
void mcAirPump();

// ===== ОТЛАДОЧНАЯ ПЕЧАТЬ =====
// Включена ли она прямо сейчас. Нужна потому, что Print::printf собирает строку ДО того,
// как её кто-то выбросит: у прошивки с журналом на карте выключенная отладка не отменяет
// работу по форматированию, а на горячих путях (каждое нажатие, каждый тик приёма) это
// уже заметно. Заглушка возвращает true — у прошивки без журнала печать идёт в консоль
// всегда, и менять ей поведение незачем.
bool mcDebugLog();

// ===== ЧАСТОТА ПРОЦЕССОРА =====
// Нужна ли прошивке полная частота прямо сейчас. Расписание держит CPU_MHZ_IDLE и
// поднимает до CPU_MHZ_FAST только на время приёма прошивки по радио — для узла, который
// лежит и слушает эфир, это правильно: считать ему нечего, а батарею берегут.
//
// Плате с экраном это не подходит. Замер на T-Deck: проверка подписи Ed25519 (она же
// разбор адверта) на 80 МГц стоит 259 мс, на полной частоте — втрое меньше; столько же
// теряют разжатие тайла карты и сравнение кадра. Поэтому прошивка может сказать, что
// полная частота ей нужна, — T-Deck отвечает «да, пока экран горит»: горящий экран и
// означает человека, который ждёт отклика. Погас — вернулись к экономии.
//
// Заглушка возвращает false: у прошивки без экрана поведение прежнее.
bool mcWantFastCpu();
// Телефонное приложение есть не у всякой платы: этот хук закрывает тот, у кого оно есть, у
// остальных работает заглушка, и это правильный путь, а не недосмотр.
//
// Хук mcButtonTick здесь был и удалён. Он пересылал вызов в buttonTick() прошивки, а логика
// кнопки переехала в ядро (src/button.cpp): пересылать стало некуда и незачем, расписание
// зовёт buttonTick() напрямую под признаком FEATURE_BUTTON. От платы кнопке нужны только пин
// и уровень — они ниже, в разделе «КНОПКА: ЖЕЛЕЗО».
void mcCompanionTick();

// ===== ПОДТВЕРЖДЕНИЕ ДОСТАВКИ =====
// Пришёл PAYLOAD_TYPE_ACK с четырёхбайтным хэшем принятого сообщения. Сверить его может
// только тот, кто это сообщение отправлял, а отправляет у нас приложение через компаньона —
// значит и сверка живёт там. Ядро лишь передаёт факт: оно не знает, что было отправлено.
// У кого приложения нет, работает заглушка, и это правильно: подтверждение ему некому
// показать.
void mcOnAckRecv(const uint8_t ack4[4]);

// ===== ЭХО СВОЕГО КАДРА =====
// Наш кадр вернулся из эфира — значит его принял и переиздал кто-то ещё, и сообщение
// ушло в сеть. Для лички судьбу сообщения показывает подтверждение от получателя
// (mcOnAckRecv), а у канального подтверждать некому: эхо — единственное, что о нём
// вообще можно узнать. hash — тот же хэш кадра, которым работает дедуп; прошивке нужны
// обычно первые четыре байта, как и у подтверждения.
void mcOnOwnFrameEcho(const uint8_t hash[32]);

// ===== ПРОВЕРКА ПОДПИСИ АДВЕРТА =====
// Прошивка может взять проверку на себя и сделать её НЕ СЕЙЧАС. Вернула true — значит
// забрала работу и сама применит результат (rememberPeerPub и companionOnAdvert);
// вернула false — ядро проверяет на месте, как и раньше.
//
// Зачем: Ed25519::verify стоит 83 мс на полной частоте и 267 на экономичной, и всё это
// время главный цикл стоит. Для платы с экраном это заметный провал, а работа —
// второстепенная: адверт не срочный, и применить его сотней миллисекунд позже никому не
// мешает. У прошивки без экрана заглушка возвращает false, и для неё ничего не меняется.
//
// msg — то, что подписано (ключ, время, прикладные данные), ровно в том виде, в каком его
// считает подписывающий. path может быть обрезан: он нужен не всем.
bool mcVerifyAdvertAsync(const uint8_t sig[64], const uint8_t pub[32], const uint8_t *msg, int mlen, const uint8_t *app,
                         int applen, uint8_t pathLen, const uint8_t *path);

// ===== ВОЗВРАТ МАРШРУТА =====
// Узел прислал дорогу ДО СЕБЯ: srcHash — его короткий хэш, pathLen — байт разметки пути
// (старшие два бита размер хэша хопа, младшие шесть число хопов), path — сами хэши.
// Хранит это тот, кто ведёт список контактов, то есть прошивка с приложением: ядро не знает,
// кому этот маршрут показывать. Довесок (extraType/extra) оригинал использует под
// подтверждение доставки.
void mcOnPathRecv(uint8_t srcHash, uint8_t pathLen, const uint8_t *path, uint8_t extraType, const uint8_t *extra,
                  int extraLen);

// ===== КНОПКА: ЖЕЛЕЗО =====
// Смысл нажатия держит ядро (src/button.cpp): серия коротких, долгое удержание, окно
// ожидания. От платы нужны только пин и уровень — их номера и подтяжка у плат разные, а у
// части плат кнопки нет вовсе.
//
// mcButtonAttach() настраивает пин и вешает прерывание, обработчик которого обязан позвать
// buttonEdgeCaptured(время, нажата) из button.h ядра — и ничего больше. Вернуть false
// означает «кнопки на этой плате нет»: ядро тогда не разбирает фронты вообще. Слабая
// заглушка так и отвечает, и это не недосмотр, а защита — на плате без кнопки опрос пина −1
// отдавал LOW, то есть «нажата навсегда».
bool mcButtonAttach();
// Уровень кнопки сейчас: true — нажата. Нужен для пересинхронизации, когда кольцо фронтов
// переполнилось дребезгом и представление ядра о кнопке разошлось с действительностью.
bool mcButtonDown();

// ===== «ВТОРЫЕ УШИ» =====
// Свежий кадр принят с радио (прошёл дедуп, не сырой fast-кадр). Вызывается на любом
// узле; смысл имеет на прошивальщике: он слышит дальние узлы лучше координатора, и его
// прошивка перекрывает хук, чтобы слать такие кадры координатору по сети (POST /ears).
// Остальные платформы живут со слабой заглушкой.
void mcOnFreshFrame(const uint8_t *buf, size_t len, float rssi, float snr);

// ===== ОТВЕТ РЕТРАНСЛЯТОРА =====
// Пришёл кадр RESPONSE: srcHash — короткий хэш ответившего, srcPub — его полный ключ (он
// есть в кэше, иначе кадр не расшифровался бы), data — расшифрованное содержимое целиком,
// то есть [метка 4][тело]. Метку ядро не толкует: какой это ответ — на вход, на состояние,
// на телеметрию — помнит тот, кто запрос отправлял, а отправляет их приложение через
// компаньона. Тело тоже разное у каждого типа запроса и нужно только приложению.
void mcOnResponseRecv(uint8_t srcHash, const uint8_t *srcPub, const uint8_t *data, int len);

// ===== СЫРОЙ ЖУРНАЛ ПРИЁМА =====
// Кадр ТОЛЬКО ЧТО принят с радио: до дедупа, до разбора, до ретрансляции. Оригинал отдаёт
// такие кадры приложению целиком (logRxRaw -> код 0x88), и приложение по ним видит, что
// его собственный пакет переиздал ретранслятор, — отсюда в переписке берётся отметка
// «принято ретранслятором». Дедуп здесь обойти обязательно: переизданная копия для нас
// дубликат, а для приложения это и есть само событие.
void mcOnRawRx(const uint8_t *raw, int len, float snr, float rssi);

// Передать кадр прошивальщику по сети, чтобы он вывел его в эфир СО СВОЕГО радио.
// Используется для ответов на пинг, пришедший через «вторые уши»: узел, которого слышит
// только прошивальщик, ответ с радио координатора не услышит. Реализует координатор
// (POST /radiotx); вернёт false, если прошивальщика нет или сеть молчит, — тогда ядро
// уходит на обычный локальный флуд.
bool mcRelayFrameToSupport(const char *supName, const uint8_t *frame, int len);


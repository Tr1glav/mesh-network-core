// Сколько миллисекунд кадр такой длины занимает эфир при ТЕКУЩИХ настройках радио.
//
// Это не оценка «вообще», а расчёт по SF, полосе, коэффициенту кодирования и преамбуле,
// которые реально выставлены: один и тот же кадр на SF8/BW62.5 и на SF11/BW125 висит в
// эфире впятеро разное время, а настройки лежат в NVS и меняются из консоли. Константа
// FRAME_AIRTIME_MS остаётся верхней границей для бюджетов, которые считаются на этапе
// сборки; там, где время кадра нужно ЗДЕСЬ И СЕЙЧАС (пауза между копиями флуда), берётся
// эта функция — короткому сообщению незачем ждать столько же, сколько самому большому.
//
// Приём тот же, что у оригинального MeshCore: там задержка повтора тоже выводится из
// getEstAirtimeFor() этого пакета, а не из общей константы.
uint32_t radioAirtimeMs(int len);

